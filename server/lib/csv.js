'use strict';
/** Escape a CSV cell and neutralise spreadsheet formula injection (=, +, -, @ …). */
function csvCell(v) {
  let s = v === null || v === undefined ? '' : String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}
module.exports = { csvCell };
